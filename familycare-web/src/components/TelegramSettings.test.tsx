import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { TelegramSettings } from './TelegramSettings'
beforeEach(() => vi.stubEnv('VITE_API_URL', 'https://api.example.test'))
afterEach(() => { cleanup(); vi.unstubAllGlobals(); vi.unstubAllEnvs() })
const response = (body: object, status = 200) => new Response(JSON.stringify(body), { status })
it('lưu chat ID trên máy chủ rồi gửi thử; không ghi chat ID vào storage', async () => {
  const fetchMock = vi.fn().mockResolvedValueOnce(response({ chat_id: '' }))
    .mockResolvedValueOnce(response({ chat_id: '-100123' }))
    .mockResolvedValueOnce(response({ sent: true }))
  vi.stubGlobal('fetch', fetchMock)
  const storage = vi.spyOn(Storage.prototype, 'setItem')
  render(<TelegramSettings />)
  await waitFor(() => expect((screen.getByLabelText('Telegram chat ID') as HTMLInputElement).disabled).toBe(false))
  expect((screen.getByRole('button', { name: 'Gửi thử' }) as HTMLButtonElement).disabled).toBe(true)
  fireEvent.change(screen.getByLabelText('Telegram chat ID'), { target: { value: '-100123' } })
  fireEvent.click(screen.getByRole('button', { name: 'Lưu kênh dự phòng' }))
  await screen.findByText('Đã lưu kênh Telegram trên máy chủ.')
  fireEvent.click(screen.getByRole('button', { name: 'Gửi thử' }))
  await screen.findByText(/Máy chủ đã gửi tin nhắn thử/)
  expect(fetchMock.mock.calls[1][0]).toBe('https://api.example.test/notify/telegram')
  expect(JSON.parse(fetchMock.mock.calls[1][1].body)).toEqual({ chat_id: '-100123' })
  expect(fetchMock.mock.calls[2][0]).toBe('https://api.example.test/notify/telegram/test')
  expect(storage).not.toHaveBeenCalled()
  storage.mockRestore()
})
it('lỗi gửi không báo thành công; thay chat ID phải lưu lại trước khi gửi', async () => {
  const fetchMock = vi.fn().mockResolvedValueOnce(response({ chat_id: '123' }))
    .mockResolvedValueOnce(response({}, 502))
  vi.stubGlobal('fetch', fetchMock)
  render(<TelegramSettings />)
  await waitFor(() => expect((screen.getByRole('button', { name: 'Gửi thử' }) as HTMLButtonElement).disabled).toBe(false))
  fireEvent.click(screen.getByRole('button', { name: 'Gửi thử' }))
  expect((await screen.findByRole('alert')).textContent).toContain('Không thể hoàn tất')
  expect(screen.queryByText(/Máy chủ đã gửi/)).toBeNull()
  fireEvent.change(screen.getByLabelText('Telegram chat ID'), { target: { value: '456' } })
  expect((screen.getByRole('button', { name: 'Gửi thử' }) as HTMLButtonElement).disabled).toBe(true)
})
it('hiển thị backend chưa sẵn sàng, không báo kênh đã hoạt động', async () => {
  vi.stubGlobal('fetch', vi.fn().mockResolvedValue(response({}, 503)))
  render(<TelegramSettings />)
  expect((await screen.findByRole('alert')).textContent).toContain('Chưa tải được')
  expect((screen.getByRole('button', { name: 'Gửi thử' }) as HTMLButtonElement).disabled).toBe(true)
})
